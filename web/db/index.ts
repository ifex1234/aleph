import { drizzle } from "drizzle-orm/postgres-js";
import postgres from "postgres";
import { sql } from "drizzle-orm";
import { config } from "dotenv";
import * as schema from "./schema";

// Dev helper: pick up the repo-root .env (gitignored). No-op elsewhere —
// dotenv never overrides vars that are already set.
config({ path: "../.env" });

const DATABASE_URL = process.env.ANALYTICS_DATABASE_URL;

let client: postgres.Sql | null = null;
let ready: Promise<void> | null = null;

function getClient(): postgres.Sql {
  if (!DATABASE_URL) {
    throw new Error("ANALYTICS_DATABASE_URL environment variable not set");
  }
  if (!client) {
    // postgres.js reads sslmode from the connection string (Neon uses
    // ?sslmode=require).
    client = postgres(DATABASE_URL, {
      idle_timeout: 20,
      max_lifetime: 60 * 30,
    });
  }
  return client;
}

export function getDb() {
  const db = drizzle(getClient(), { schema });
  if (!ready) ready = ensureSchema(db);
  return { db, ready };
}

async function ensureSchema(db: ReturnType<typeof drizzle>): Promise<void> {
  // Zero-migration bootstrap: idempotent, mirrors db/schema.ts. For schema
  // changes, prefer drizzle-kit migrations (npm run db:generate && db:migrate).
  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS analytics_events (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_type text NOT NULL,
      anon_id text,
      platform text,
      dedupe_key text UNIQUE,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await db.execute(sql`
    CREATE INDEX IF NOT EXISTS idx_analytics_events_type_created
    ON analytics_events (event_type, created_at)
  `);
  await db.execute(sql`
    CREATE INDEX IF NOT EXISTS idx_analytics_events_platform
    ON analytics_events (platform, event_type)
  `);
}
