/**
 * Generates src/brand/icons.ts from the authentic lucide SVGs in
 * ../motion-assets/icons (server-rendered from the app's exact lucide build).
 * Inner markup is kept verbatim; the wrapper supplies sizing/color so icons
 * can be tinted per scene. Re-run: bun run icons
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "motion-assets", "icons");
const out = join(here, "..", "src", "brand", "icons.ts");

const camel = (name) =>
  name
    .replace(/\.svg$/, "")
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const entries = [];
for (const file of readdirSync(src).filter((f) => f.endsWith(".svg")).sort()) {
  const raw = readFileSync(join(src, file), "utf8");
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .trim()
    // Keep the file readable in source control.
    .replace(/></g, ">\n    <");
  entries.push({ name: camel(file), inner });
}

const body = entries
  .map(({ name, inner }) => `  ${name}: \`\n    ${inner}\n  \`,`)
  .join("\n");

const file = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Source: ../motion-assets/icons/*.svg (authentic lucide icons from the app).

export const ICONS = {
${body}
} as const;

export type IconName = keyof typeof ICONS;
`;

mkdirSync(join(here, "..", "src", "brand"), { recursive: true });
writeFileSync(out, file);
console.log(`Wrote ${out} (${entries.length} icons)`);
